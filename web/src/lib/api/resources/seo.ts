import { api } from "../client";
import type {
  BlogImpact,
  BlogRun,
  BlogSchedule,
  BlogSiteOption,
  BlogStatus,
  Compare,
  CrawlerKey,
  CrawlerStatus,
  CrawlJob,
  CrawlOverview,
  CrawlPageQuery,
  CrawlPages,
  Finding,
  FindingList,
  FindingQuery,
  KeywordRow,
  KpiStudio,
  LinkOptions,
  MerchantSeoSite,
  Overview,
  QueueResult,
  Report,
  ReportsCenter,
  SeoStatus,
  SiteDetail,
  SiteInput,
  SitePages,
  SitesList,
  SyncRun,
  Watchdog,
} from "@/features/seo/types";

/** SEO (API modules/seo). Read-only towards Google and the client websites. */
export const seo = {
  status: (): Promise<SeoStatus> => api.get("/seo/status"),
  connect: (returnTo: "seo" | "settings" = "seo"): Promise<{ url: string }> => api.post(`/seo/connect?returnTo=${returnTo}`),
  disconnect: (): Promise<void> => api.del("/seo/connection"),
  sync: (): Promise<SyncRun> => api.postLong("/seo/sync"),
  runs: (limit = 10): Promise<SyncRun[]> => api.getList<SyncRun>("/seo/sync-runs", { limit }),
  loadSampleData: (): Promise<{ sites: number }> => api.post("/seo/sample-data"),
  removeSampleData: (): Promise<{ removed: number }> => api.del("/seo/sample-data"),

  overview: (): Promise<Overview> => api.get("/seo/overview"),
  watchdog: (limit = 40): Promise<Watchdog> => api.get("/seo/watchdog", { limit }),

  sites: (): Promise<SitesList> => api.get("/seo/sites"),
  addSite: (domain: string, name?: string): Promise<{ id: string; domain: string; name: string }> => api.post("/seo/sites", { domain, name: name || undefined }),
  updateSite: (id: string, body: SiteInput): Promise<unknown> => api.patch(`/seo/sites/${id}`, body),
  deleteSite: (id: string): Promise<void> => api.del(`/seo/sites/${id}`),
  site: (id: string): Promise<SiteDetail> => api.get(`/seo/sites/${id}`),
  pages: (id: string): Promise<SitePages> => api.get(`/seo/sites/${id}/pages`),
  crawl: (id: string): Promise<CrawlOverview> => api.get(`/seo/sites/${id}/crawl`),
  crawlPages: (id: string, q: CrawlPageQuery): Promise<CrawlPages> => api.get(`/seo/sites/${id}/crawl/pages`, { ...q }),
  rescore: (id: string): Promise<unknown> => api.post(`/seo/sites/${id}/rescore`),
  keywords: (id: string): Promise<{ data: KeywordRow[]; month: string | null; prevMonth: string | null }> => api.get(`/seo/sites/${id}/keywords`),
  pagespeed: (id: string): Promise<{ checked: number; errors: string[]; health: number | null }> => api.post(`/seo/sites/${id}/pagespeed`),
  addKeyword: (id: string, keyword: string): Promise<{ id: string }> => api.post(`/seo/sites/${id}/keywords`, { keyword }),
  deleteKeyword: (keywordId: string): Promise<void> => api.del(`/seo/keywords/${keywordId}`),
  linkOptions: (q: string): Promise<LinkOptions> => api.get("/seo/link-options", { q }),

  findings: (q: FindingQuery): Promise<FindingList> => api.get("/seo/findings", { ...q }),
  updateFinding: (id: string, body: { state?: string; outcome?: "fixed" | "dismissed"; ownerId?: string | null; note?: string }): Promise<Finding> =>
    api.patch(`/seo/findings/${id}`, body),

  reportsCenter: (days: number): Promise<ReportsCenter> => api.get("/seo/reports/center", { days }),
  generateReport: (siteId: string, period?: { periodStart: string; periodEnd: string }): Promise<Report> => api.post(`/seo/sites/${siteId}/reports`, period ?? {}),
  report: (id: string): Promise<Report> => api.get(`/seo/reports/${id}`),
  signOff: (id: string): Promise<Report> => api.post(`/seo/reports/${id}/sign-off`),
  updateNextSteps: (id: string, nextSteps: string[]): Promise<Report> => api.patch(`/seo/reports/${id}/next-steps`, { nextSteps }),
  updateSummary: (id: string, paragraphs: string[], section?: string): Promise<Report> =>
    api.patch(`/seo/reports/${id}/summary`, section ? { paragraphs, section } : { paragraphs }),
  send: (id: string, recipients: string[]): Promise<Report> => api.post(`/seo/reports/${id}/send`, { recipients }),
  testEmail: (to?: string): Promise<{ sentTo: string; from: string }> => api.post("/seo/email/test", to ? { to } : {}),

  kpis: (): Promise<KpiStudio> => api.get("/seo/kpis"),
  updateKpi: (key: string, body: { target?: string; status?: string; name?: string }): Promise<unknown> => api.patch(`/seo/kpis/${key}`, body),
  addKpi: (body: { set: number; name: string; grader: string; target: string; source: string }): Promise<unknown> => api.post("/seo/kpis", body),
  deleteKpi: (key: string): Promise<void> => api.del(`/seo/kpis/${key}`),

  compare: (ids: string[]): Promise<Compare> => api.get("/seo/compare", { ids: ids.join(",") }),
  merchantSites: (merchantId: string): Promise<{ data: MerchantSeoSite[] }> => api.get(`/merchants/${merchantId}/seo`),

  // Blog Impact (API modules/seo/blog_router.py)
  blogStatus: (): Promise<BlogStatus> => api.get("/seo/blogs/status"),
  saveBlogSchedule: (body: { enabled: boolean; times: string[] }): Promise<BlogSchedule> => api.put("/seo/blogs/schedule", body),
  refreshBlogs: (): Promise<BlogRun> => api.postLong("/seo/blogs/refresh"),
  blogSites: (): Promise<BlogSiteOption[]> => api.getList<BlogSiteOption>("/seo/blogs/sites"),
  crawlerStatus: (): Promise<CrawlerStatus> => api.get("/seo/crawler/status"),
  queueCrawl: (body: { siteIds?: string[]; all?: boolean }): Promise<QueueResult> => api.post("/seo/crawler/crawl", body),
  cancelCrawl: (jobId: string): Promise<CrawlJob> => api.post(`/seo/crawler/jobs/${jobId}/cancel`),
  crawlerKeys: (): Promise<CrawlerKey[]> => api.getList<CrawlerKey>("/seo/crawler/keys"),
  createCrawlerKey: (name: string): Promise<CrawlerKey & { key: string }> => api.post("/seo/crawler/keys", { name }),
  revokeCrawlerKey: (id: string): Promise<CrawlerKey> => api.del(`/seo/crawler/keys/${id}`),
  blogImpact: (siteId: string, days: number, country: "all" | "us" = "all"): Promise<BlogImpact> =>
    api.get(`/seo/blogs/sites/${siteId}`, { days, country }),
  saveBrandTerms: (siteId: string, terms: string[]): Promise<{ brandTerms: string[] }> => api.put(`/seo/blogs/sites/${siteId}/brand-terms`, { terms }),
};
